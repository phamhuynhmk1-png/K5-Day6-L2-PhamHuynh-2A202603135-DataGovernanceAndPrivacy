"""Ablation on the DEV split: drop one defect family at a time and re-measure (manual dev labels).

    python -m tools.ablation_t02 --out reports/t02_ablation_dev.md

Same frozen thresholds as configs/lab.yaml; a dropped family simply gets margin -inf. Uses the repo's
evaluator (eval_t02) via tools.dev_eval_t02. DEV numbers are optimistic (thresholds fitted on dev).
"""
from __future__ import annotations

import argparse
import tempfile
from pathlib import Path

import numpy as np
import pandas as pd

from src.common.io import load_config
from src.t02_qc import DEFECT_TYPES, add_dark_ratio, extract_features, score_images
from tools.dev_eval_t02 import dev_eval

FIX = Path("fixtures/t02_raw_qc")


def _metrics(scored: pd.DataFrame) -> dict:
    with tempfile.TemporaryDirectory() as td:
        p = Path(td) / "ranked_review.csv"
        scored[["image_id", "score", "pred_defect_type"]].to_csv(p, index=False)
        m, _ = dev_eval(p)
    get = lambda name: m.loc[(m.metric == name) & (m.slice == "all"), "value"].iloc[0]
    fa = m[(m.metric == "False alarm in top-B")]
    return {"Recall@20": get("Defect Recall@B"), "Precision@20": get("Precision@B"),
            "Type acc": get("Defect-type accuracy (GT defects)"),
            "False alarms in top-20": int(fa.numerator.sum())}


def run() -> pd.DataFrame:
    params = load_config("configs/lab.yaml")["params"]
    imgs = pd.read_csv(FIX / "images.csv")
    feats = add_dark_ratio(extract_features(imgs[imgs.split == "dev"], FIX), params["ref_luma_by_light"])
    full = score_images(feats, params["thresholds"])
    rows = [{"variant": "PoC (all 4 families)", **_metrics(full)}]
    for fam in DEFECT_TYPES:
        s = full.copy()
        s[f"m_{fam}"] = -np.inf
        cols = [f"m_{f}" for f in DEFECT_TYPES]
        s["score"] = s[cols].max(axis=1)
        s["pred_defect_type"] = np.where(s.score > 0, s[cols].idxmax(axis=1).str[2:], "none")
        rows.append({"variant": f"without {fam}", **_metrics(s)})
    return pd.DataFrame(rows)


def _md(t: pd.DataFrame) -> str:
    fmt = lambda v: f"{v:.3f}" if isinstance(v, float) else str(v)
    lines = ["| " + " | ".join(t.columns) + " |", "|" + "---|" * len(t.columns)]
    lines += ["| " + " | ".join(fmt(v) for v in row) + " |" for row in t.itertuples(index=False)]
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=None)
    a = ap.parse_args(argv)
    t = run()
    md = ("# T02 ablation (DEV split, manual labels, B=20; generated by tools/ablation_t02.py)\n\n"
          "Ceiling for Recall@20 on dev = 20/28 = 0.714 (28 defects, 20 review slots).\n\n"
          + _md(t) + "\n")
    print(md)
    if a.out:
        Path(a.out).write_text(md, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
